    await click('Close');
    T.select(P.pidOfService('Dnscache'));
    item(T.menu(), 'End process tree').action(); await wait(60);
    t('End process tree asks first', dlgText().includes('Do you want to end the process tree of svchost.exe?'));
    await click('Cancel');

